// Release signing is optional: it only activates when a local, gitignored
// keystore.properties is present (see docs/development.md). Without one, `assembleRelease`
// still builds - just unsigned - so cloning this repo never requires anyone else's keystore.
val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties().apply {
    if (keystorePropertiesFile.exists()) {
        keystorePropertiesFile.inputStream().use { load(it) }
    }
}

